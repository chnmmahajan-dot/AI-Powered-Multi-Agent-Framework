
import json
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from playwright.sync_api import TimeoutError as PlaywrightTimeoutError


class BrowserExecutor:
    """
    Executes structured browser instructions using Playwright.

    AI provides structured instructions.
    This class translates those instructions into Playwright actions.

    It does not execute arbitrary Python code generated by AI.
    """

    SUPPORTED_ACTIONS = {
        "navigate",
        "click",
        "fill",
        "press",
        "select_option",
        "check",
        "uncheck",
        "verify_text",
        "verify_visible",
        "verify_url",
        "wait_for",
    }

    DEFAULT_TIMEOUT = 5000
    MAX_TIMEOUT = 30000

    def __init__(
        self,
        page: Any,
        artifacts_dir: str = "artifacts",
    ):
        self.page = page
        self.artifacts_dir = Path(artifacts_dir)

        self.screenshot_dir = (
            self.artifacts_dir / "failure_screenshots"
        )
        self.report_dir = (
            self.artifacts_dir / "execution_reports"
        )

    def _require_field(
        self,
        data: dict,
        field: str,
        action: str,
    ) -> Any:
        value = data.get(field)

        if value is None or value == "":
            raise ValueError(
                f"Action '{action}' requires a non-empty "
                f"'{field}' field."
            )

        return value

    def _get_timeout(self, step: dict) -> int:
        timeout = step.get(
            "timeout",
            self.DEFAULT_TIMEOUT,
        )

        if (
            not isinstance(timeout, int)
            or isinstance(timeout, bool)
            or timeout < 1
            or timeout > self.MAX_TIMEOUT
        ):
            raise ValueError(
                f"Timeout must be an integer between 1 and "
                f"{self.MAX_TIMEOUT} milliseconds."
            )

        return timeout

    def _get_locator(self, target: dict):
        """Convert a structured target into a Playwright locator."""

        if not isinstance(target, dict):
            raise ValueError(
                "The target must be an object."
            )

        strategy = self._require_field(
            target,
            "by",
            "locator",
        )

        value = self._require_field(
            target,
            "value",
            "locator",
        )

        exact = target.get("exact", False)

        if not isinstance(exact, bool):
            raise ValueError(
                "'exact' must be a boolean."
            )

        if strategy == "role":
            role = self._require_field(
                target,
                "role",
                "role locator",
            )

            return self.page.get_by_role(
                role,
                name=value,
                exact=exact,
            )

        if strategy == "label":
            return self.page.get_by_label(
                value,
                exact=exact,
            )

        if strategy == "placeholder":
            return self.page.get_by_placeholder(
                value,
                exact=exact,
            )

        if strategy == "text":
            return self.page.get_by_text(
                value,
                exact=exact,
            )

        if strategy == "test_id":
            return self.page.get_by_test_id(value)

        if strategy == "css":
            return self.page.locator(value)

        raise ValueError(
            f"Unsupported locator strategy: '{strategy}'"
        )

    def _verify_text(
        self,
        expected: str,
        timeout: int,
    ) -> None:
        """
        Verify that at least one matching text element is visible.
        """

        text_locator = self.page.get_by_text(expected)

        try:
            text_locator.first.wait_for(
                state="visible",
                timeout=timeout,
            )
            return

        except PlaywrightTimeoutError:
            matching_elements = text_locator.count()

            for index in range(matching_elements):
                if text_locator.nth(index).is_visible():
                    return

            raise

    def execute_step(self, step: dict) -> dict:
        """Execute a single browser instruction."""

        if not isinstance(step, dict):
            raise ValueError(
                "Every test step must be an object."
            )

        action = self._require_field(
            step,
            "action",
            "step",
        )

        if action not in self.SUPPORTED_ACTIONS:
            raise ValueError(
                f"Unsupported action: '{action}'. "
                f"Supported actions: {sorted(self.SUPPORTED_ACTIONS)}"
            )

        timeout = self._get_timeout(step)

        if action == "navigate":
            url = self._require_field(
                step,
                "url",
                action,
            )

            if not isinstance(url, str):
                raise ValueError(
                    "The navigation URL must be a string."
                )

            self.page.goto(
                url,
                wait_until="domcontentloaded",
                timeout=timeout,
            )

        elif action == "click":
            locator = self._get_locator(
                self._require_field(
                    step,
                    "target",
                    action,
                )
            )

            locator.click(timeout=timeout)

        elif action == "fill":
            locator = self._get_locator(
                self._require_field(
                    step,
                    "target",
                    action,
                )
            )

            value = self._require_field(
                step,
                "value",
                action,
            )

            if not isinstance(value, str):
                raise ValueError(
                    "'value' must be a string."
                )

            locator.fill(
                value,
                timeout=timeout,
            )

        elif action == "press":
            locator = self._get_locator(
                self._require_field(
                    step,
                    "target",
                    action,
                )
            )

            key = self._require_field(
                step,
                "value",
                action,
            )

            locator.press(
                key,
                timeout=timeout,
            )

        elif action == "select_option":
            locator = self._get_locator(
                self._require_field(
                    step,
                    "target",
                    action,
                )
            )

            value = self._require_field(
                step,
                "value",
                action,
            )

            locator.select_option(
                value,
                timeout=timeout,
            )

        elif action == "check":
            locator = self._get_locator(
                self._require_field(
                    step,
                    "target",
                    action,
                )
            )

            locator.check(timeout=timeout)

        elif action == "uncheck":
            locator = self._get_locator(
                step,
                "target",
                action,
            )

            locator.uncheck(timeout=timeout)

        elif action == "verify_text":
            expected = self._require_field(
                step,
                "expected",
                action,
            )

            if not isinstance(expected, str):
                raise ValueError(
                    "'expected' must be a string."
                )

            self._verify_text(
                expected,
                timeout,
            )

        elif action == "verify_visible":
            locator = self._get_locator(
                self._require_field(
                    step,
                    "target",
                    action,
                )
            )

            locator.wait_for(
                state="visible",
                timeout=timeout,
            )

        elif action == "verify_url":
            expected = self._require_field(
                step,
                "expected",
                action,
            )

            if not isinstance(expected, str):
                raise ValueError(
                    "'expected' must be a string."
                )

            self.page.wait_for_function(
                "(expected) => window.location.href.includes(expected)",
                expected,
                timeout=timeout,
            )

        elif action == "wait_for":
            locator = self._get_locator(
                self._require_field(
                    step,
                    "target",
                    action,
                )
            )

            locator.wait_for(
                state="visible",
                timeout=timeout,
            )

        return {
            "action": action,
            "status": "passed",
        }

    def _get_page_state(self) -> dict:
        """Safely capture the current browser URL and page title."""

        state = {
            "url": None,
            "title": None,
        }

        try:
            state["url"] = self.page.url
        except Exception:
            pass

        try:
            state["title"] = self.page.title()
        except Exception:
            pass

        return state

    def _capture_failure_screenshot(
        self,
        test_case_id: str,
        step_number: int,
    ) -> dict:
        """Attempt to capture a screenshot without hiding the original error."""

        try:
            self.screenshot_dir.mkdir(
                parents=True,
                exist_ok=True,
            )

            safe_test_id = "".join(
                character
                if character.isalnum() or character in "-_"
                else "_"
                for character in str(test_case_id)
            )

            screenshot_path = (
                self.screenshot_dir
                / f"{safe_test_id}_step_{step_number}.png"
            )

            self.page.screenshot(
                path=str(screenshot_path),
                full_page=True,
            )

            return {
                "screenshot_path": str(screenshot_path),
                "screenshot_error": None,
            }

        except Exception as screenshot_error:
            return {
                "screenshot_path": None,
                "screenshot_error": str(screenshot_error),
            }

    def _save_execution_report(
        self,
        report: dict,
        test_case_id: str,
    ) -> str:
        """Save the execution report as JSON and return its path."""

        self.report_dir.mkdir(
            parents=True,
            exist_ok=True,
        )

        safe_test_id = "".join(
            character
            if character.isalnum() or character in "-_"
            else "_"
            for character in str(test_case_id)
        )

        report_path = (
            self.report_dir
            / f"{safe_test_id}_execution_report.json"
        )

        report["report_path"] = str(report_path)

        with report_path.open(
            "w",
            encoding="utf-8",
        ) as report_file:
            json.dump(
                report,
                report_file,
                indent=4,
                ensure_ascii=False,
                default=str,
            )

        return str(report_path)

    def execute_test_plan(self, test_plan: dict) -> dict:
        """
        Execute all test steps.

        Stop when a step fails, capture failure information,
        attempt a screenshot, and save a JSON execution report.
        """

        if not isinstance(test_plan, dict):
            raise ValueError(
                "Test plan must be an object."
            )

        test_case_id = self._require_field(
            test_plan,
            "test_case_id",
            "test plan",
        )

        title = self._require_field(
            test_plan,
            "title",
            "test plan",
        )

        steps = self._require_field(
            test_plan,
            "steps",
            "test plan",
        )

        if not isinstance(steps, list) or not steps:
            raise ValueError(
                "The test plan must contain at least one step."
            )

        started_at = datetime.now(
            timezone.utc
        ).isoformat()

        test_start = time.perf_counter()
        results = []

        print(f"\nStarting test: {title}")
        print(f"Test ID: {test_case_id}")
        print(f"Total steps: {len(steps)}")

        for index, step in enumerate(
            steps,
            start=1,
        ):
            action = (
                step.get("action", "unknown")
                if isinstance(step, dict)
                else "unknown"
            )

            print(
                f"\nExecuting step {index}: {action}"
            )

            step_start = time.perf_counter()

            try:
                result = self.execute_step(step)

                result["step_number"] = index
                result["duration_ms"] = round(
                    (time.perf_counter() - step_start) * 1000,
                    2,
                )

                results.append(result)

                print(f"Step {index}: PASSED")

            except Exception as error:
                step_duration = round(
                    (time.perf_counter() - step_start) * 1000,
                    2,
                )

                print(f"Step {index}: FAILED")
                print(f"Reason: {error}")

                failed_step = {
                    "step_number": index,
                    "action": action,
                    "status": "failed",
                    "duration_ms": step_duration,
                    "error": {
                        "type": type(error).__name__,
                        "message": str(error),
                    },
                }

                results.append(failed_step)

                screenshot_result = (
                    self._capture_failure_screenshot(
                        test_case_id,
                        index,
                    )
                )

                failure_details = {
                    "step_number": index,
                    "action": action,
                    "status": "failed",
                    "error": {
                        "type": type(error).__name__,
                        "message": str(error),
                    },
                    "browser_state": self._get_page_state(),
                    "screenshot_path": screenshot_result[
                        "screenshot_path"
                    ],
                    "screenshot_error": screenshot_result[
                        "screenshot_error"
                    ],
                }

                finished_at = datetime.now(
                    timezone.utc
                ).isoformat()

                execution_result = {
                    "test_case_id": test_case_id,
                    "title": title,
                    "status": "failed",
                    "started_at": started_at,
                    "finished_at": finished_at,
                    "duration_ms": round(
                        (time.perf_counter() - test_start) * 1000,
                        2,
                    ),
                    "total_steps": len(steps),
                    "passed_steps": index - 1,
                    "failed_steps": 1,
                    "failed_step_number": index,
                    "step_results": results,
                    "failure_details": failure_details,
                }

                try:
                    self._save_execution_report(
                        execution_result,
                        test_case_id,
                    )
                except Exception as report_error:
                    execution_result["report_path"] = None
                    execution_result["report_error"] = str(
                        report_error
                    )

                failure = RuntimeError(
                    f"Test '{test_case_id}' failed at step "
                    f"{index} (action: {action}): {error}"
                )

                failure.execution_result = execution_result
                failure.failure_details = failure_details

                raise failure from error

        finished_at = datetime.now(
            timezone.utc
        ).isoformat()

        execution_result = {
            "test_case_id": test_case_id,
            "title": title,
            "status": "passed",
            "started_at": started_at,
            "finished_at": finished_at,
            "duration_ms": round(
                (time.perf_counter() - test_start) * 1000,
                2,
            ),
            "total_steps": len(steps),
            "passed_steps": len(results),
            "failed_steps": 0,
            "step_results": results,
        }

        try:
            self._save_execution_report(
                execution_result,
                test_case_id,
            )
        except Exception as report_error:
            execution_result["report_path"] = None
            execution_result["report_error"] = str(
                report_error
            )

        print(
            f"\nTest completed successfully: {test_case_id}"
        )

        return execution_result
