
from typing import Any


class BrowserExecutor:
    """
    Executes AI-generated browser instructions using Playwright.

    The AI provides structured instructions.
    This class translates those instructions into Playwright actions.

    It does not execute arbitrary Python code generated by AI.
    """

    SUPPORTED_ACTIONS = {
        "navigate",
        "click",
        "fill",
        "press",
        "select_option",
        "check",
        "uncheck",
        "verify_text",
        "verify_visible",
        "verify_url",
        "wait_for",
    }

    DEFAULT_TIMEOUT = 5000
    MAX_TIMEOUT = 30000

    def __init__(self, page: Any):
        """
        Receive an existing Playwright Page object.

        The page can be supplied by a Playwright test fixture.
        """
        self.page = page

    def _require_field(
        self,
        data: dict,
        field: str,
        action: str,
    ) -> Any:
        """Check that a required field exists and is not empty."""

        value = data.get(field)

        if value is None or value == "":
            raise ValueError(
                f"Action '{action}' requires a non-empty '{field}' field."
            )

        return value

    def _get_timeout(self, step: dict) -> int:
        """Get and validate the timeout for a browser action."""

        timeout = step.get("timeout", self.DEFAULT_TIMEOUT)

        if (
            not isinstance(timeout, int)
            or isinstance(timeout, bool)
            or timeout < 1
            or timeout > self.MAX_TIMEOUT
        ):
            raise ValueError(
                f"Timeout must be an integer between 1 and "
                f"{self.MAX_TIMEOUT} milliseconds."
            )

        return timeout

    def _get_locator(self, target: dict):
        """
        Convert a structured target into a Playwright locator.

        Supported locator strategies:
        - role
        - label
        - placeholder
        - text
        - test_id
        - css
        """

        if not isinstance(target, dict):
            raise ValueError("The target must be an object.")

        strategy = self._require_field(
            target,
            "by",
            "locator",
        )

        value = self._require_field(
            target,
            "value",
            "locator",
        )

        exact = target.get("exact", False)

        if not isinstance(exact, bool):
            raise ValueError("'exact' must be a boolean.")

        if strategy == "role":
            role = self._require_field(
                target,
                "role",
                "role locator",
            )

            return self.page.get_by_role(
                role,
                name=value,
                exact=exact,
            )

        if strategy == "label":
            return self.page.get_by_label(
                value,
                exact=exact,
            )

        if strategy == "placeholder":
            return self.page.get_by_placeholder(
                value,
                exact=exact,
            )

        if strategy == "text":
            return self.page.get_by_text(
                value,
                exact=exact,
            )

        if strategy == "test_id":
            return self.page.get_by_test_id(value)

        if strategy == "css":
            return self.page.locator(value)

        raise ValueError(
            f"Unsupported locator strategy: '{strategy}'"
        )

    def execute_step(self, step: dict) -> dict:
        """Execute one browser instruction."""

        if not isinstance(step, dict):
            raise ValueError("Every test step must be an object.")

        action = self._require_field(
            step,
            "action",
            "step",
        )

        if action not in self.SUPPORTED_ACTIONS:
            raise ValueError(
                f"Unsupported action: '{action}'. "
                f"Supported actions: {sorted(self.SUPPORTED_ACTIONS)}"
            )

        timeout = self._get_timeout(step)

        if action == "navigate":
            url = self._require_field(step, "url", action)

            if not isinstance(url, str):
                raise ValueError("The navigation URL must be a string.")

            self.page.goto(
                url,
                wait_until="domcontentloaded",
                timeout=timeout,
            )

        elif action == "click":
            locator = self._get_locator(
                self._require_field(step, "target", action)
            )

            locator.click(timeout=timeout)

        elif action == "fill":
            locator = self._get_locator(
                self._require_field(step, "target", action)
            )

            value = self._require_field(step, "value", action)

            if not isinstance(value, str):
                raise ValueError("'value' must be a string.")

            locator.fill(value, timeout=timeout)

        elif action == "press":
            locator = self._get_locator(
                self._require_field(step, "target", action)
            )

            key = self._require_field(step, "value", action)

            locator.press(key, timeout=timeout)

        elif action == "select_option":
            locator = self._get_locator(
                self._require_field(step, "target", action)
            )

            value = self._require_field(step, "value", action)

            locator.select_option(value, timeout=timeout)

        elif action == "check":
            locator = self._get_locator(
                self._require_field(step, "target", action)
            )

            locator.check(timeout=timeout)

        elif action == "uncheck":
            locator = self._get_locator(
                self._require_field(step, "target", action)
            )

            locator.uncheck(timeout=timeout)

        elif action == "verify_text":
            expected = self._require_field(
                step,
                "expected",
                action,
            )

            if not isinstance(expected, str):
                raise ValueError("'expected' must be a string.")

            self.page.get_by_text(expected).first.wait_for(
                state="visible",
                timeout=timeout,
            )

        elif action == "verify_visible":
            locator = self._get_locator(
                self._require_field(step, "target", action)
            )

            locator.wait_for(
                state="visible",
                timeout=timeout,
            )

        elif action == "verify_url":
            expected = self._require_field(
                step,
                "expected",
                action,
            )

            if not isinstance(expected, str):
                raise ValueError("'expected' must be a string.")

            self.page.wait_for_function(
                "(expected) => window.location.href.includes(expected)",
                expected,
                timeout=timeout,
            )

        elif action == "wait_for":
            locator = self._get_locator(
                self._require_field(step, "target", action)
            )

            locator.wait_for(
                state="visible",
                timeout=timeout,
            )

        return {
            "action": action,
            "status": "passed",
        }

    def execute_test_plan(self, test_plan: dict) -> dict:
        """
        Execute all steps in an AI-generated test plan.

        Stops immediately if a step fails.
        """

        if not isinstance(test_plan, dict):
            raise ValueError("Test plan must be an object.")

        test_case_id = self._require_field(
            test_plan,
            "test_case_id",
            "test plan",
        )

        title = self._require_field(
            test_plan,
            "title",
            "test plan",
        )

        steps = self._require_field(
            test_plan,
            "steps",
            "test plan",
        )

        if not isinstance(steps, list) or not steps:
            raise ValueError(
                "The test plan must contain at least one step."
            )

        results = []

        print(f"\nStarting test: {title}")
        print(f"Test ID: {test_case_id}")
        print(f"Total steps: {len(steps)}")

        for index, step in enumerate(steps, start=1):
            action = (
                step.get("action", "unknown")
                if isinstance(step, dict)
                else "unknown"
            )

            print(f"\nExecuting step {index}: {action}")

            try:
                result = self.execute_step(step)
                result["step_number"] = index
                results.append(result)

                print(f"Step {index}: PASSED")

            except Exception as error:
                print(f"Step {index}: FAILED")
                print(f"Reason: {error}")

                raise RuntimeError(
                    f"Test '{test_case_id}' failed at step "
                    f"{index} (action: {action}): {error}"
                ) from error

        print(f"\nTest completed successfully: {test_case_id}")

        return {
            "test_case_id": test_case_id,
            "title": title,
            "status": "passed",
            "total_steps": len(steps),
            "passed_steps": len(results),
            "failed_steps": 0,
            "step_results": results,
        }
